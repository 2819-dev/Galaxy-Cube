CHAR_W = 5
CHAR_H = 7
CHAR_GAP = 1


def text_width(text: str, scale: int = 1) -> int:
    if not text:
        return 0
    return len(text) * (CHAR_W * scale + CHAR_GAP * scale) - CHAR_GAP * scale


def draw_text(
    draw: ImageDraw.ImageDraw,
    xy: tuple[int, int],
    text: str,
    fill: int = 1,
    scale: int = 1,
) -> None:
    x, y = xy
    for ch in text:
        cols = _GLYPHS.get(ch) or _GLYPHS.get(ch.upper()) or (0x7F, 0x41, 0x41, 0x41, 0x7F)
        for cx, col in enumerate(cols):
            for cy in range(7):
                if col & (1 << cy):
                    px = x + cx * scale
                    py = y + cy * scale
                    if scale == 1:
                        draw.point((px, py), fill=fill)
                    else:
                        draw.rectangle(
                            (px, py, px + scale - 1, py + scale - 1),
                            fill=fill,
                        )
        x += (CHAR_W + CHAR_GAP) * scale


def measure(text: str, scale: int = 1) -> tuple[int, int]:
    return text_width(text, scale), CHAR_H * scale


def blit_text(
    image: Image.Image,
    xy: tuple[int, int],
    text: str,
    fill: int = 1,
    scale: int = 1,
) -> None:
    draw = ImageDraw.Draw(image)
    draw_text(draw, xy, text, fill=fill, scale=scale)
